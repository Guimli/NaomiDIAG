#!/usr/bin/env python3
"""gen_glyphs.py <lang> -- glyphs of the non-ASCII characters a language uses.

Scans src/lang/<lang>.h for every character above 0x7F in its string
literals and extracts their bitmaps from GNU Unifont (tools/fonts/
unifont.hex.gz, https://unifoundry.com -- GPL-2.0-or-later with the font
embedding exception, or SIL OFL 1.1) into src/lang/glyphs_<lang>.h.

ASCII keeps NaomiDIAG's own 8x8 font, drawn x2 in a 16x16 cell. A Unifont
glyph fills the same cell: a half-width one (8x16, Latin letters with
accents, Cyrillic, ...) drawn two pixels wide, a full-width one (16x16,
kana, hanzi, kanji) as it is. Only the glyphs the language uses are kept,
so a ROM carries its own few dozen to few hundred.

Usage: gen_glyphs.py <lang>      (e.g. de, ja, zh)
"""
import gzip, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "lang")
FONT = os.path.join(HERE, "fonts", "unifont.hex.gz")


def literals(path):
    """Characters of every C string literal in the file (escapes resolved)."""
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = []
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', text):
        s = m.group(1)
        s = re.sub(r"\\(.)", lambda e: {"n": "\n", "r": "\r", "t": "\t"}.get(e.group(1), e.group(1)), s)
        out.append(s)
    return "".join(out)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    lang = sys.argv[1]
    chars = sorted({ord(c) for c in literals(os.path.join(SRC, lang + ".h")) if ord(c) > 0x7F})
    if any(c > 0xFFFF for c in chars):
        sys.exit("characters beyond the BMP are not supported")
    font = {}
    if chars:
        if not os.path.exists(FONT):
            sys.exit(f"{FONT} missing: download unifont-<version>.hex.gz from "
                     "https://unifoundry.com/unifont/ there")
        want = set(chars)
        with gzip.open(FONT, "rt") as f:
            for line in f:
                cp, bits = line.strip().split(":")
                cp = int(cp, 16)
                if cp in want:
                    font[cp] = bytes.fromhex(bits)
    missing = [c for c in chars if c not in font]
    if missing:
        sys.exit("no Unifont glyph for " + " ".join(f"U+{c:04X}" for c in missing))
    out = [f"/* Generated by tools/gen_glyphs.py {lang} -- do not edit.",
           " * Non-ASCII glyphs of this language, from GNU Unifont (GPL-2.0-or-later",
           " * with the font embedding exception, or SIL OFL 1.1). Sorted by code point;",
           " * a half-width glyph is 16 bytes (8x16), a full-width one 32 (16x16), one",
           " * row per byte or byte pair, leftmost pixel in the top bit. */",
           f"#ifndef GLYPHS_{lang.upper()}_H", f"#define GLYPHS_{lang.upper()}_H",
           f"#define GLYPH_COUNT {len(chars)}u"]
    if chars:
        offs, data = [], bytearray()
        for c in chars:
            offs.append(len(data))
            data += font[c]
        out.append("static const glyph_ent glyph_tab[GLYPH_COUNT] = {")
        for c, o in zip(chars, offs):
            out.append(f"    {{ 0x{c:04X}, {o}, {1 if len(font[c]) == 32 else 0} }},   /* {chr(c)} */")
        out.append("};")
        out.append("static const unsigned char glyph_bits[] = {")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};")
    else:
        out.append("static const glyph_ent glyph_tab[1] = { { 0, 0, 0 } };")
        out.append("static const unsigned char glyph_bits[1] = { 0 };")
    out += ["#endif", ""]
    dst = os.path.join(SRC, f"glyphs_{lang}.h")
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    nfull = sum(1 for c in chars if len(font[c]) == 32)
    print(f"{dst}: {len(chars)} glyphs ({nfull} full-width), "
          f"{sum(len(font[c]) for c in chars)} bytes")


main()
